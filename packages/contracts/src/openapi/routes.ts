/**
 * Every HTTP route of the API, described from the schemas the API validates
 * with. The OpenAPI document (docs/openapi.json) is generated from this list,
 * and an API test fails if a controller's routes and this list disagree on a
 * path, method, success status, session or role.
 */

export type HttpMethod = "get" | "post" | "put" | "patch" | "delete";

/** Who may call a route. Staff routes need at least `role`. */
export type Access =
  | { readonly kind: "staff"; readonly role: Role }
  | { readonly kind: "attendee" }
  | { readonly kind: "public" }
  /** Public, but acts on the session named by the refresh cookie. */
  | { readonly kind: "refresh" };

/** A response body that is not JSON. */
export interface RawBody {
  readonly contentType: string;
  readonly description: string;
}

export interface RouteSpec {
  readonly method: HttpMethod;
  /** OpenAPI path, relative to /api/v1: `/events/{eventId}`. */
  readonly path: string;
  readonly operationId: string;
  readonly tag: string;
  readonly summary: string;
  readonly description?: string;
  readonly access: Access;
  readonly params?: Readonly<Record<string, z.ZodType>>;
  readonly query?: z.ZodObject;
  readonly body?: z.ZodType;
  /** Requires `If-Match` with the resource's current `ETag`. */
  readonly ifMatch?: true;
  /** Accepts an `Idempotency-Key`, so a retried create is not repeated. */
  readonly idempotencyKey?: true;
  readonly status: number;
  /** The success body; none for an empty response. */
  readonly response?: z.ZodType | RawBody;
  /** Other documented outcomes besides problem details. */
  readonly otherResponses?: Readonly<
    Record<
      number,
      { readonly description: string; readonly schema?: z.ZodType }
    >
  >;
}

